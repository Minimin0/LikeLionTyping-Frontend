/** 우리 학교이므로 항상 첫 번째로 출제한다. */
const FIXED_FIRST = '성결대'

/**
 * 첫 번째는 항상 성결대, 나머지는 중복 없이 랜덤으로 뽑는다.
 *
 * 이 추첨은 Mock 서버가 게임 세션을 만드는 시점에 단 한 번만 호출된다.
 * 컴포넌트에서 호출하면 리렌더마다 목록이 새로 섞여 게임이 망가지므로 주의.
 */
export function pickUniversities(count = 20): string[] {
  const rest = UNIVERSITIES.filter((name) => name !== FIXED_FIRST)

  // Fisher-Yates 셔플 — filter가 이미 새 배열을 만들었으므로 원본은 훼손되지 않는다.
  for (let i = rest.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[rest[i], rest[j]] = [rest[j], rest[i]]
  }

  return [FIXED_FIRST, ...rest.slice(0, count - 1)]
}
